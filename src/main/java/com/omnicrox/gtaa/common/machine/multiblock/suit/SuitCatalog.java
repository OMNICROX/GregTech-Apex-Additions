package com.omnicrox.gtaa.common.machine.multiblock.suit;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.omnicrox.gtaa.GTAA;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The suits the Suit Fabrication Station can make (gtapexadditions/suit_station.json, generated by
 * tools/hero_kits.py). Same list on client and server: only suits whose armor exists in the pack are kept.
 */
public final class SuitCatalog {

    private SuitCatalog() {}

    public record Entry(String suit, String name, int tier, String kit, List<String> abilities,
                        List<Item> armor, List<ItemStack> parts, int circuit) {

        /** Id of the station recipe made by GTAASuitStation (GT puts the recipe type in front). */
        public ResourceLocation recipeId() {
            return GTAA.id("suit_fabrication/suit/" + suit.replace(':', '/'));
        }
    }

    private static List<Entry> entries;
    private static Map<String, Entry> bySuit;

    public static synchronized List<Entry> all() {
        if (entries == null) load();
        return entries;
    }

    public static Entry get(String suit) {
        all();
        return suit == null ? null : bySuit.get(suit);
    }

    /** The station entry whose recipe id this is, or null. */
    public static Entry byRecipe(ResourceLocation id) {
        if (id == null || !id.getNamespace().equals(GTAA.MOD_ID)) return null;
        String path = id.getPath();
        if (path.startsWith("suit_fabrication/")) path = path.substring("suit_fabrication/".length());
        if (!path.startsWith("suit/")) return null;
        String rest = path.substring(5);
        int slash = rest.indexOf('/');
        return slash < 0 ? null : get(rest.substring(0, slash) + ":" + rest.substring(slash + 1));
    }

    private static Item item(String id) {
        Item it = BuiltInRegistries.ITEM.get(new ResourceLocation(id));
        return it == Items.AIR ? null : it;
    }

    private static void load() {
        List<Entry> list = new ArrayList<>();
        try (InputStream in = GTAA.class.getResourceAsStream("/gtapexadditions/suit_station.json")) {
            if (in != null) {
                for (JsonElement el : JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonArray()) {
                    Entry e = parse(el.getAsJsonObject());
                    if (e != null) list.add(e);
                }
            }
        } catch (Exception ex) {
            GTAA.LOGGER.warn("Suit station list unreadable: {}", ex.toString());
        }
        list.sort((a, b) -> a.tier != b.tier ? Integer.compare(a.tier, b.tier) : a.name.compareToIgnoreCase(b.name));
        entries = Collections.unmodifiableList(list);
        bySuit = new LinkedHashMap<>();
        for (Entry e : list) bySuit.put(e.suit, e);
    }

    private static Entry parse(JsonObject s) {
        List<Item> armor = new ArrayList<>();
        for (JsonElement a : s.getAsJsonArray("armor")) {
            Item it = item(a.getAsString());
            if (it == null) return null;
            armor.add(it);
        }
        List<ItemStack> parts = new ArrayList<>();
        for (JsonElement ie : s.getAsJsonArray("ingredients")) {
            JsonObject i = ie.getAsJsonObject();
            if (!i.has("item")) continue;
            Item it = item(i.get("item").getAsString());
            if (it == null) return null;
            parts.add(new ItemStack(it, i.get("count").getAsInt()));
        }
        List<String> abilities = new ArrayList<>();
        if (s.has("abilities")) for (JsonElement a : s.getAsJsonArray("abilities")) abilities.add(a.getAsString());
        return new Entry(s.get("suit").getAsString(), s.get("name").getAsString(),
                Math.max(1, Math.min(4, s.get("tier").getAsInt())),
                s.has("kit") && !s.get("kit").isJsonNull() ? s.get("kit").getAsString() : "",
                abilities, armor, parts, s.has("circuit") ? s.get("circuit").getAsInt() : 0);
    }
}
